"""Index address mentions for changed saved-function ranges; no semantic coverage claim."""
import hashlib
import json
import re
from audit_thrash_loader_difference import ROOT


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    source=ROOT/'analysis/evidence/audits/original-modern-function-diff.json'
    inventory=json.loads(source.read_text())
    for key in ('original','official_modern'):
        row=inventory['binaries'][key]
        assert digest(ROOT/row['path'])==row['sha256']
    saved=inventory['function_inventory']
    assert digest(ROOT/saved['path'])==saved['sha256']
    excluded={'original-modern-differences.md','original-modern-function-index.md','original-modern-outside-function-index.md','original-modern-initialized-data-index.md','original-modern-string-index.md','original-modern-relocation-index.md'}
    docs=sorted(p for p in (ROOT/'analysis').glob('original-modern-*.md') if p.name not in excluded)
    docs.append(ROOT/'analysis/og-modern-x87-precision.md')
    sources=[]
    for path in docs:
        addresses=sorted({int(m.group(1),16) for m in re.finditer(r'(?<![0-9a-zA-Z])(?:0x)?(00[4-9aA][0-9a-fA-F]{5})(?![0-9a-zA-Z])',path.read_text())})
        sources.append({'path':str(path.relative_to(ROOT)),'sha256':digest(path),'addresses':addresses})
    rows=[]
    for function in inventory['functions']:
        if function['status']!='different_same_VA_bytes':continue
        ranges=[(int(a,16),int(b,16)) for a,b in function['ranges']]
        references=[]
        for doc in sources:
            matches=[a for a in doc['addresses'] if any(lo<=a<hi for lo,hi in ranges)]
            if matches:references.append({'path':doc['path'],'entry_mentioned':int(function['entry'],16) in matches,'addresses':[f'{a:08x}' for a in matches]})
        rows.append({**function,'report_address_references':references})
    assert len(rows)==inventory['counts']['different_same_VA_bytes']==361
    linked=sum(bool(row['report_address_references']) for row in rows)
    manifest={'kind':'changed-function-report-address-index','source':str(source.relative_to(ROOT)),'source_sha256':digest(source),'baselines':{k:inventory['binaries'][k] for k in ('original','official_modern')},'source_documents':[{k:v for k,v in d.items() if k!='addresses'} for d in sources],'counts':{'changed_saved_function_ranges':len(rows),'with_address_mentions':linked,'without_address_mentions':len(rows)-linked},'limits':['Address mentions only; not verified semantic analysis or completed coverage.','Ranges and names come from saved Modern analysis, not inferred original counterparts.','Excludes main summary/catalog and generated function/outside-body indexes to avoid self-support.','Missing entries, moved functions, changed bytes outside saved bodies, data/assets/imports and indirect semantics need separate investigations.'],'functions':rows}
    out=ROOT/'analysis/evidence/audits/function-report-address-index.json'
    out.write_text(json.dumps(manifest,indent=2)+'\n')
    lines=['# Changed-function address reference index','','Generated by `python3 analysis/scripts/build_function_difference_index.py` from the [pinned byte comparison](evidence/audits/original-modern-function-diff.json). [Machine-readable index](evidence/audits/function-report-address-index.json).','',f'All **{len(rows)} changed saved Modern function entries** are listed: **{linked}** have an address mention in a comparison chapter and **{len(rows)-linked}** have none. These counts measure search/navigation links, **not analysed functions, semantic coverage or completion**.','', 'A linked chapter may only mention a caller, unknown or partial span. Read its scope and evidence before deciding what is established. An unlinked row may still have research using another address format, a moved counterpart or notes outside these chapters.','', 'Original/official executable hashes and saved Modern function-inventory hash are checked when regenerating. Names/ranges remain Modern analysis metadata; same-address byte differences do not establish original function correspondence. The main summary, release-note catalog and generated function/outside-body indexes are excluded as reference sources.','', 'The original code comparison also records **21,926 changed code bytes outside the saved Modern function ranges**. This table does not classify those bytes, enumerate all patch changes or cover data, assets, DLLs, imports and resources. See the [main comparison](original-modern-differences.md).','','| Modern entry | Saved analysis label | Body bytes | Changed bytes | Chapters mentioning an address in the saved body |','|---|---|---:|---:|---|']
    for row in rows:
        links=[]
        for ref in row['report_address_references']:
            name=ref['path'].split('/')[-1]
            label=name.removesuffix('.md').removeprefix('original-modern-')
            links.append(f'[{label}]({name})')
        label=row['name'].replace('|','\\|').replace('`','')
        lines.append(f"| `{row['entry']}` | {label} | {row['bytes']} | {row['changed_bytes']} | {', '.join(links) if links else 'No address mention found'} |")
    (ROOT/'analysis/original-modern-function-index.md').write_text('\n'.join(lines)+'\n')
    print(json.dumps(manifest['counts']))


if __name__=='__main__':main()
