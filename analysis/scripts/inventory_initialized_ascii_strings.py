"""NUL-delimited ASCII text-value inventory; candidate text is not behavior."""
import hashlib
import json
import re
import pefile
from audit_thrash_loader_difference import ROOT,SPECS


def main():
    result={'kind':'initialized-data-ascii-string-value-comparison',
        'rule':'DGROUP/.data only; printable ASCII 20h..7eh, minimum 6 bytes, NUL terminated, preceded by NUL or section start',
        'binaries':{}}
    maps={}
    for label,(relative,expected,_) in SPECS.items():
        raw=(ROOT/relative).read_bytes();assert hashlib.sha256(raw).hexdigest()==expected
        pe=pefile.PE(data=raw)
        name=b'DGROUP' if label=='original' else b'.data'
        section=next(s for s in pe.sections if s.Name.rstrip(b'\0')==name)
        assert section.PointerToRawData>0
        data=section.get_data();strings={}
        for match in re.finditer(rb'[\x20-\x7e]{6,}\x00',data):
            offset=match.start()
            if offset and data[offset-1]!=0:continue
            value=match.group()[:-1].decode('ascii')
            strings.setdefault(value,[]).append(f'{0x400000+section.VirtualAddress+offset:08x}')
        maps[label]=strings
        result['binaries'][label]={'path':relative,'sha256':expected,
            'section':name.decode(),'section_sha256':hashlib.sha256(data).hexdigest(),
            'strings_by_value':strings,'unique_values':len(strings)}
    old,new=maps['original'],maps['official_modern']
    added=sorted(new.keys()-old.keys());removed=sorted(old.keys()-new.keys())
    shared=sorted(old.keys()&new.keys())
    moved=[s for s in shared if old[s]!=new[s]]
    result['counts']={'modern_only_values':len(added),'original_only_values':len(removed),
        'shared_values':len(shared),'shared_values_with_different_address_lists':len(moved)}
    result['modern_only_values']=added;result['original_only_values']=removed
    result['shared_values_with_different_address_lists']=moved
    result['limits']=['Candidate text only; not dependency, reachability, feature removal or user-visible behavior proof.',
        'Excludes short, non-ASCII, multiline/control-containing, non-NUL-bounded strings and all other PE sections/assets/DLLs.',
        'Value comparison ignores moves for added/removed lists; offsets are version-specific and not semantic counterpart proof.',
        'No target execution or executable/Ghidra changes.']
    (ROOT/'analysis/evidence/audits/initialized-ascii-string-differences.json').write_text(json.dumps(result,indent=2)+'\n')
    lines=['# Initialized-data ASCII string difference index','',
        'Generated by `python3 analysis/scripts/inventory_initialized_ascii_strings.py`. [Full value/address inventory](evidence/audits/initialized-ascii-string-differences.json). [Main comparison](original-modern-differences.md).','',
        f"The bounded scan finds **{len(added)} Modern-only values**, **{len(removed)} original-only values**, and **{len(shared)} shared values**. Of the shared values, **{len(moved)}** have different address lists. Values repeated at several addresses are counted once. These are text candidates, not counts of changed features.",'',
        'Scope: file-backed original `DGROUP` and Modern `.data`; printable ASCII bytes20h..7eh, at least six characters, terminated by NUL and preceded by NUL or section start. Shorter, non-ASCII, multiline/control-containing text, code-embedded strings, resources and external assets are excluded. Presence does not establish a reachable reference; absence under this rule does not prove the text or feature is gone from the complete package.','',
        'Added/removed means absent by exact value from the other scanned data section. A moved identical value remains shared. Shared address-list differences include moves, duplicate additions/removals and other location changes; their exact lists are in JSON. Same-address bytes can belong to different objects.','']
    for title,values,mapping in [('Modern-only text values',added,new),('Original-only text values',removed,old)]:
        lines += [f'## {title}','','| Addresses | Exact candidate text |','|---|---|']
        for value in values:
            safe=value.replace('&','&amp;').replace('<','&lt;').replace('>','&gt;').replace('|','&#124;').replace('`','&#96;').replace('\\','&#92;')
            lines.append('| '+', '.join(f'`{a}`' for a in mapping[value])+' | <code>'+safe+'</code> |')
        lines.append('')
    lines += ['## Interpretation','',
        'Use candidates to locate code/data investigations, then bind actual references, initialization and consumers before assigning a mechanism. For example, DLL/export names alone do not establish successful dynamic loading; option labels do not establish defaults; removed diagnostic text does not establish removal of every related check. Existing detailed chapters remain the evidence for those conclusions.','',
        '**Inventory status: done for this deterministic scan. Confidence: verified bytes within the stated rule. Semantic attribution: incomplete.** No target instructions or external application operations were executed.']
    (ROOT/'analysis/original-modern-string-index.md').write_text('\n'.join(lines)+'\n')
    print(json.dumps(result['counts']))


if __name__=='__main__':main()
