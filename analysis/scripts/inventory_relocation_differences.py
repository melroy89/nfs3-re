"""PE base-relocation-site inventory, separate from target pointer semantics."""
import hashlib,json,struct
from collections import Counter
import pefile
from audit_thrash_loader_difference import ROOT,SPECS


def site(pe,raw,va):
    rva=va-pe.OPTIONAL_HEADER.ImageBase
    section=pe.get_section_by_rva(rva)
    assert section is not None
    name=section.Name.rstrip(b'\0').decode('ascii')
    offset=rva-section.VirtualAddress
    backed=bool(section.PointerToRawData and offset+4<=section.SizeOfRawData
                and section.PointerToRawData+offset+4<=len(raw))
    row={'va':f'{va:08x}','section':name,'file_backed':backed}
    if backed:
        at=section.PointerToRawData+offset
        row.update(file_offset=f'{at:08x}',operand_hex=raw[at:at+4].hex())
    return row


def main():
    result={'kind':'pe-highlow-relocation-site-comparison','binaries':{}}
    sets=[];images=[];files=[]
    for label,(relative,expected,_) in SPECS.items():
        raw=(ROOT/relative).read_bytes();assert hashlib.sha256(raw).hexdigest()==expected
        pe=pefile.PE(data=raw);assert pe.OPTIONAL_HEADER.ImageBase==0x400000
        entries=[e for block in pe.DIRECTORY_ENTRY_BASERELOC for e in block.entries]
        types=Counter(e.type for e in entries);assert set(types)=={0,3}
        addresses=[0x400000+e.rva for e in entries if e.type==3]
        assert len(addresses)==len(set(addresses))
        sites=set(addresses);sets.append(sites);images.append(pe);files.append(raw)
        directory=pe.OPTIONAL_HEADER.DATA_DIRECTORY[5]
        section=pe.get_section_by_rva(directory.VirtualAddress)
        assert directory.VirtualAddress==section.VirtualAddress
        assert not any(section.get_data()[directory.Size:])
        block_bytes=sum(b.struct.SizeOfBlock for b in pe.DIRECTORY_ENTRY_BASERELOC)
        assert block_bytes==directory.Size
        result['binaries'][label]={'path':relative,'sha256':expected,
            'relocation_directory_va':f'{0x400000+directory.VirtualAddress:08x}',
            'directory_bytes':directory.Size,'section_raw_bytes':section.SizeOfRawData,
            'section_bytes_outside_directory':section.SizeOfRawData-directory.Size,
            'outside_directory_bytes_all_zero':True,
            'block_count':len(pe.DIRECTORY_ENTRY_BASERELOC),
            'entry_type_counts':dict(sorted(types.items())),
            'highlow_count':len(sites),
            'highlow_sorted_site_digest':hashlib.sha256(b''.join(struct.pack('<I',x) for x in sorted(sites))).hexdigest()}
    old,new=sets;removed=sorted(old-new);added=sorted(new-old);shared=sorted(old&new)
    assert (len(old),len(new),len(removed),len(added),len(shared))==(46398,45371,2205,1178,44193)
    result['original_only_sites']=[site(images[0],files[0],va) for va in removed]
    result['modern_only_sites']=[site(images[1],files[1],va) for va in added]
    changed=[]
    for va in shared:
        a,b=[site(pe,raw,va) for pe,raw in zip(images,files)]
        if a.get('operand_hex')!=b.get('operand_hex') or a['file_backed']!=b['file_backed']:
            changed.append({'va':f'{va:08x}','original':a,'official_modern':b})
    result['shared_sites_with_changed_file_operands']=changed
    result['counts']={'removed_sites':len(removed),'added_sites':len(added),
        'shared_sites':len(shared),'shared_sites_with_changed_file_operands':len(changed)}
    result['limits']=['Site is the DWORD loader adjusts, not the pointer target it contains.',
        'Same-site presence/bytes do not prove semantic object or runtime address identity.',
        'HIGHLOW metadata only; no complete instruction/reference validation or loader execution.',
        'Unbacked storage is not read from file offset zero or asserted to remain zero after startup.']
    (ROOT/'analysis/evidence/audits/relocation-differences.json').write_text(json.dumps(result,indent=2)+'\n')
    a,b=[result['binaries'][k] for k in ('original','official_modern')]
    lines=['# PE base-relocation differences','',
        'Generated by `python3 analysis/scripts/inventory_relocation_differences.py`. [Complete added/removed sites and changed shared operands](evidence/audits/relocation-differences.json). [Main comparison](original-modern-differences.md).','',
        '| Property | Supplied original | Official Modern |','|---|---:|---:|']
    for title,key in [('HIGHLOW sites','highlow_count'),('Relocation blocks','block_count'),
        ('Directory bytes','directory_bytes'),('Section raw bytes','section_raw_bytes'),
        ('Section bytes outside directory','section_bytes_outside_directory')]:
        lines.append(f'| {title} | {a[key]:,} | {b[key]:,} |')
    lines += ['',f'There are **{len(removed):,} removed**, **{len(added):,} added** and **{len(shared):,} shared** HIGHLOW sites. **{len(changed):,} shared sites** have different file-backed operand bytes or backing classification. Removed/added means table membership at the relocation-site address, not allocation/free or a count of changed features. Every added/removed site has its VA, section and file bytes when available in JSON.','',
        '## Exact size accounting','',
        'The block/entry layout and HIGHLOW/ABSOLUTE interpretation follow the [Microsoft PE specification](https://learn.microsoft.com/en-us/windows/win32/debug/pe-format#the-reloc-section-image-only). Byte counts below are independently parsed from the two pinned files.','',
        'Original has46,398 HIGHLOW entries plus156 ABSOLUTE padding entries across331 blocks. Modern has45,371 HIGHLOW entries plus155 ABSOLUTE padding entries across332 blocks. Each entry occupies2 bytes and each block has an8-byte header. Removing1,028 total entries saves2,056 bytes; the additional block header adds8, yielding a2,048-byte directory reduction. The section raw size falls by1,536 bytes because verified zero padding outside the directory increases from500 to1,012. These counts describe serialized PE metadata; padding entries are not pointer adjustments.','',
        'The directory moves from VA00a19000 to00a1f000. Growth of uninitialized storage and placement/alignment are distinct from relocation-site membership. Neither the relocation section size nor a table entry count measures initialized game-data capacity.','',
        '## Interpretation for comparison and reconstruction','',
        'A HIGHLOW site identifies the32-bit operand to which the loader applies the image-base delta. It does not identify the object pointed to, establish that a function is reachable, or prove that the metadata matches every decoded instruction. Code removal, moved instructions and data descriptor changes can alter these sites independently of feature counts. Compare semantic callers/data separately.','',
        'All29 relocation sites inside first reconstruction leaf00485c30 remain identical across the three pinned baselines, as the [sample comparison](original-modern-reconstruction-baselines.md) verifies. The [initialized-data index](original-modern-initialized-data-index.md) separately annotates relocation overlap with changed bytes. Those bounded checks do not qualify arbitrary extracted functions for relocation or game integration.','',
        '**Inventory status: done; confidence: verified PE records and file operands. Semantic and loader/runtime validation: incomplete.** No executable/Ghidra changes, code export, compilation or target execution occurred.']
    (ROOT/'analysis/original-modern-relocation-index.md').write_text('\n'.join(lines)+'\n')
    print(json.dumps(result['counts']))


if __name__=='__main__':main()
