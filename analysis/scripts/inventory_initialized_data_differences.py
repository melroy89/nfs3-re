"""Complete same-VA initialized-data byte map; no inferred data types."""
import hashlib
import json
import pefile
from audit_thrash_loader_difference import ROOT,SPECS


def sha(data):return hashlib.sha256(data).hexdigest()


def main():
    result={'kind':'initialized-data-byte-difference-inventory','binaries':{}}
    sections=[];relocations=[]
    for label,(relative,expected,_) in SPECS.items():
        raw=(ROOT/relative).read_bytes();assert sha(raw)==expected
        pe=pefile.PE(data=raw)
        name=b'DGROUP' if label=='original' else b'.data'
        section=next(s for s in pe.sections if s.Name.rstrip(b'\0')==name)
        assert section.PointerToRawData>0 and section.VirtualAddress==0x136000
        assert section.SizeOfRawData==226816
        data=section.get_data();assert len(data)==226816
        sections.append(data)
        relocs=sorted(pe.OPTIONAL_HEADER.ImageBase+entry.rva
                     for block in pe.DIRECTORY_ENTRY_BASERELOC for entry in block.entries
                     if entry.type==3 and section.VirtualAddress<=entry.rva<section.VirtualAddress+len(data))
        relocations.append(relocs)
        result['binaries'][label]={'path':relative,'sha256':expected,
            'section':name.decode(),'start':'00536000','end_exclusive':'0056d600',
            'raw_offset':f'{section.PointerToRawData:08x}','raw_bytes':len(data),
            'section_sha256':sha(data),'highlow_relocation_sites': [f'{va:08x}' for va in relocs]}
    old,new=sections;start=0x536000
    runs=[];i=0
    while i<len(old):
        if old[i]==new[i]:i+=1;continue
        lo=i
        while i<len(old) and old[i]!=new[i]:i+=1
        hi=i
        runs.append({'start':f'{start+lo:08x}','end_exclusive':f'{start+hi:08x}',
            'changed_bytes':hi-lo,'original_hex':old[lo:hi].hex(),
            'modern_hex':new[lo:hi].hex(),
            'overlapping_highlow_relocations':{
                label:[f'{va:08x}' for va in sites if va<start+hi and start+lo<va+4]
                for label,sites in zip(('original','official_modern'),relocations)}})
    changed=sum(row['changed_bytes'] for row in runs);assert changed==11576
    result['counts']={'section_bytes':len(old),'same_va_changed_bytes':changed,
        'contiguous_changed_runs':len(runs),
        'runs_overlapping_original_highlow_relocations':sum(bool(r['overlapping_highlow_relocations']['original']) for r in runs),
        'runs_overlapping_modern_highlow_relocations':sum(bool(r['overlapping_highlow_relocations']['official_modern']) for r in runs)}
    result['limits']=['Exact same-VA byte differences, not matched semantic objects or complete data reconstruction.',
        'Covers only initialized DGROUP/.data file bytes; excludes BSS, imports, resources, reloc table bytes, code-embedded data and DLL/assets.',
        'HIGHLOW overlap identifies loader-adjusted DWORD operands, not pointer types, valid targets or full ownership.',
        'Startup/later writes and computed aliases can change effective state; no target execution.']
    result['runs']=runs
    output=ROOT/'analysis/evidence/audits/initialized-data-differences.json'
    output.write_text(json.dumps(result,indent=2)+'\n')
    ranked=sorted(runs,key=lambda r:(-r['changed_bytes'],r['start']))
    lines=['# Initialized-data difference address index','',
        'Generated by `python3 analysis/scripts/inventory_initialized_data_differences.py`. [Complete run inventory](evidence/audits/initialized-data-differences.json). [Main comparison](original-modern-differences.md).','',
        f'The pinned original `DGROUP` and official Modern `.data` occupy the same file-backed VA range **00536000..0056d600** (226,816 bytes). Exactly **{changed:,} bytes** differ, in **{len(runs):,} contiguous changed runs**. Every differing byte is represented once in the JSON, with original/Modern bytes and addresses. Runs split at every equal byte; they are not structures, strings or logical change counts.','',
        'The manifest retains both executable and section hashes, file offsets and all HIGHLOW relocation sites within each data section. Changed runs overlapping those loader-adjusted DWORDs are annotated. Equal addresses do not prove the same object survives between versions; relocated/moved tables and storage reuse require explicit counterpart work.','',
        '## Largest contiguous byte runs','',
        '| Start | End exclusive | Changed bytes | Original relocation operands overlapping | Modern relocation operands overlapping |',
        '|---|---|---:|---:|---:|']
    for row in ranked[:25]:
        r=row['overlapping_highlow_relocations']
        lines.append(f"| `{row['start']}` | `{row['end_exclusive']}` | {row['changed_bytes']} | {len(r['original'])} | {len(r['official_modern'])} |")
    lines += ['', '## Interpretation and remaining work','',
        'A changed zero or printable byte is not sufficient to assign a type or feature. HIGHLOW overlap indicates a relocation operand, not that a changed byte itself is a complete pointer. The stored bytes here precede loader relocation, startup and later initialization writes. Unknown layouts may remain opaque; a data map does not establish reconstruction readiness.','',
        'Use existing chapters for already grounded examples: [language fallback](original-modern-language-table.md), [menu callback descriptors](original-modern-menu-callback-table.md), [HUD presets](original-modern-hud-layout.md), [frame settings](original-modern-frame-setting.md) and [music tables](original-modern-music-selection.md). Further investigation must map the actual producers/consumers and asset identity for selected remaining runs rather than inventing semantics from byte patterns.','',
        '**Inventory status: done; evidence confidence: verified static bytes and PE relocation annotations. Semantic classification: incomplete.** BSS, code-embedded tables, imports, resources and external components have separate evidence; this index does not cover them or any runtime state. Executables, Ghidra and maintained C were not modified.']
    (ROOT/'analysis/original-modern-initialized-data-index.md').write_text('\n'.join(lines)+'\n')
    print(json.dumps(result['counts']))


if __name__=='__main__':main()
